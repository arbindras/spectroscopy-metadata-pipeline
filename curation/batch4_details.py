def _spec2(rid, exp, vol, counts, nsamples, nholes, fmt, missing, cary, extra_remark=""):
    wl = {"ammonium": "640", "phosphate": "885", "silica": "812"}
    analytes = list(counts)
    reagents = {"ammonium": "ammonium: phenol-hypochlorite indophenol blue",
                "phosphate": "phosphate: ammonium molybdate / ascorbic acid molybdenum blue",
                "silica": "silica: molybdate / metol-sulfite (molybdenum blue)"}
    rec(rid,
        fmt=fmt,
        npts=f"{sum(counts.values())} concentration results (" + ", ".join(f"{a} {n}" for a, n in counts.items()) + f") for {nsamples} IW samples in {nholes} holes; calibration absorbance readings in supplementary files",
        missing=missing,
        prep="Yes (absorbance converted to concentration via standard curve)",
        prep_methods="1) IW subsample diluted and reacted with colour reagent (" + "; ".join(reagents[a] for a in analytes) + "); 2) absorbance read at fixed wavelength; 3) linear calibration against standard series; 4) dilution correction",
        target="Dissolved " + ", ".join(analytes) + " concentration in interstitial water vs depth",
        mode="Single-wavelength absorbance (double-beam UV-Vis, cuvette)",
        wl="; ".join(f"{a} {wl[a]}" for a in analytes),
        res="Spectral bandwidth 1.5 nm (Cary reads reports)",
        make=f"Agilent/Varian {cary} UV-Vis",
        path="1 cm cuvette (standard; not stated in dataset)",
        ts="No (depth series)",
        chemo="No (univariate linear calibration)",
        refs=_IODP_REF[vol],
        remarks=f"Paper PDF is the {_IODP_PAPER[vol]}; data_by_hole tables give Analyte, Concentration (uM), Text ID, Test No., comments ('ship split, untreated')" + extra_remark,
        cond="Shipboard laboratory, room temperature colour development",
        absorb="Linear absorbance-concentration calibration slopes in calibration workbooks",
        refm="Gravimetric NH4Cl / KH2PO4 / Na2SiF6 standard series and check standards",
        gold=NA, peaks=NA,
        struct="Ammonium [NH4+]; phosphate [O-]P(=O)([O-])[O-]" + ("; silicic acid O[Si](O)(O)O" if "silica" in analytes else "") + "; indophenol blue / molybdenum blue chromophores")


