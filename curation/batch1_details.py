def _exo2(rid, iso, dsname, nstates, ntrans, numin, numax, tmax, xs, ref, extra_fmt=""):
    rec(rid,
        fmt="ZIP: ExoMol-format line list (.states.bz2, .trans.bz2), partition function (.pf), definitions (.def), README/.md" + (
            "; ExoMolOP opacities: TauREx cross sections (.h5, R=15000), petitRADTRANS (.h5) / NEMESIS (.kta) / ARCiS (.fits.gz) k-tables (R=1000), 0.3-50 um" if xs else "") + extra_fmt,
        npts=f"{nstates:,} states, {ntrans:,} transitions" + ("; 594 cross-section spectra (22 p x 27 T) x 76,743 bins" if xs else "") + f"; Q(T) 1-{tmax} K in 1 K steps",
        missing="No",
        prep="Not applicable (computed/empirical line list)", prep_methods=NA,
        target=f"Spectroscopic line list (energies, Einstein A coefficients, lifetimes) of {iso} for modelling hot astrophysical atmospheres",
        mode="Theoretical/empirical (" + ("ab initio + fitted potential, Duo/LEVEL" if dsname == "Barton" else "empirical from laboratory FT spectra (Bernath group), MoLLIST") + ")",
        wl=f">={1e7/numax:.0f} (line positions {numin}-{numax} cm-1, mid-IR to microwave)" + ("; opacity grids 300-50000" if xs else ""),
        res="Line-by-line (infinite); cross sections R=15000, k-tables R=1000" if xs else "Line-by-line (no instrumental resolution)",
        make=NA, path=NA, ts="No",
        chemo="No",
        refs=ref + "; Tennyson et al. (2020) The 2020 release of the ExoMol database, JQSRT 255:107228, doi:10.1016/j.jqsrt.2020.107228" + ("; Chubb et al. (2021) ExoMolOP, A&A 646:A21" if xs else ""),
        remarks=f"Dataset name {dsname}; maximum line-list temperature {tmax} K; default Lorentzian HWHM 0.07 cm-1/bar, n=0.5",
        cond=f"Valid for T up to {tmax} K" + ("; cross sections at 27 T (100-3400 K) x 22 p (1e-5 - 100 bar)" if xs else ""),
        absorb="Einstein A coefficients per transition (absolute intensities)" + ("; absorption cross sections cm2/molecule" if xs else ""),
        refm="Laboratory line positions (MARVEL/experimental) used to tune model" if dsname == "Barton" else "Laboratory Fourier-transform emission spectra",
        gold=NA,
        peaks=f"Rovibrational band structure of {iso}" + (" incl. A-X, B-X, E-X electronic systems" if iso == "40Ca1H" else " (X 1Sigma+ ground state, fundamental + overtones)"),
        struct=f"{iso} diatomic")


